import csv
from pathlib import Path

import mpmath as mp


mp.mp.dps = 55
M = mp.mpf
BASE = tuple(map(M, (100.0, 120.0, 0.20, 0.30, 0.40)))
RATE = M(0.05)
with Path(__file__).with_name("basket-nodes.csv").open() as f:
    NODES = [(M(float.fromhex(row["z"])), M(float.fromhex(row["weight"]))) for row in csv.DictReader(f)]


def cdf(z):
    return mp.erfc(-z / mp.sqrt(2)) / 2


def price(a, b, va, vb, rho):
    sd = vb * mp.sqrt((1 - rho) * (1 + rho))
    total = M(0)
    for node, weight in NODES:
        strike = 220 - a * mp.exp(RATE + va * (node - va / 2))
        conditional_log_b = mp.log(b) + RATE - vb * vb / 2 + vb * rho * node
        mean_b = mp.exp(conditional_log_b + sd * sd / 2)
        if strike <= 0:
            call = mean_b - strike
        else:
            d2 = (conditional_log_b - mp.log(strike)) / sd
            call = mean_b * cdf(d2 + sd) - strike * cdf(d2)
        total += weight * call
    return mp.exp(-RATE) * total / 2


def derivative(*indices):
    orders = [indices.count(i) for i in range(5)]
    return mp.diff(price, BASE, orders)


def output(values):
    return ", ".join(mp.nstr(x, 22) for x in values)


print("#pragma once\n\n#include <array>\n\nnamespace TapePerfS0 {")
print("    // Generated by basket-reference.py using mpmath at 55 decimal digits.")
print("    inline constexpr double BASKET_PRICE = " + output([price(*BASE)]) + ";")
print("    inline constexpr std::array<double, 5> BASKET_GRADIENT{" + output([derivative(i) for i in range(5)]) + "};")
print("    inline constexpr std::array<std::array<double, 5>, 5> BASKET_HESSIAN{{")
for i in range(5):
    print("        {" + output([derivative(i, j) for j in range(5)]) + "},")
print("    }};")
print("    inline constexpr std::array<std::array<double, 2>, 48> BASKET_NODES{{")
with Path(__file__).with_name("basket-nodes.csv").open() as f:
    for row in csv.DictReader(f):
        print(f'        {{{row["z"]}, {row["weight"]}}},')
print("    }};\n} // namespace TapePerfS0")
