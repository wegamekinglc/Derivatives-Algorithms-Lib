namespace {
    constexpr int REPEATS = 10;

    void Check(const Fixings_& source, const String_& encoded) {
        const auto restored = handle_cast<Fixings_>(JSON::ReadString(encoded, false));
        REQUIRE(restored && restored->Name() == source.Name() && restored->vals_ == source.vals_, "Fixings JSON roundtrip mismatch");
        for (const auto& [time, value] : source.vals_)
            REQUIRE(LookupFixing(restored->vals_, time) == value, "Fixings JSON exact lookup mismatch");
    }

    Fixings_ DailyFixings(int count) {
        Fixings_::vals_t values;
        for (int i = 0; i < count; ++i)
            values.emplace(DateTime_(Date_(2025, 1, 1).AddDays(i), 0.), 100. + i / 8.);
        return Fixings_("perf-fixings", values);
    }

    void CheckPreciseKeys() {
        Fixings_::vals_t values;
        double value = 0.;
        for (double fraction :
             {0., std::numeric_limits<double>::denorm_min(), .1 / 86400., .2 / 86400., std::nextafter(.2 / 86400., 1.), std::nextafter(1., 0.)})
            values.emplace(DateTime_(Date_(2026, 2, 14), fraction), ++value);
        const Fixings_ source("subseconds", values);
        const auto encoded = JSON::WriteString(source);
        Check(source, encoded);
        REQUIRE(JSON::WriteString(*JSON::ReadString(encoded, false)) == encoded, "Fixings JSON rewrite is unstable");
        std::cout << "precise_keys=6 exact_lookup=verified rewrite_stable=verified\n";
    }

    template <class F_> std::int64_t Batch(F_ action, int loops) {
        const auto start = std::chrono::steady_clock::now();
        for (int i = 0; i < loops; ++i)
            action();
        return std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::steady_clock::now() - start).count();
    }

    template <class F_> void Measure(const std::string& name, F_ action) {
        int loops = 1;
        while (Batch(action, loops) < 10000000 && loops < 65536)
            loops *= 2;
        Batch(action, loops);
        Batch(action, loops);
        std::array<std::int64_t, REPEATS> samples{}, perCall{};
        for (int i = 0; i < REPEATS; ++i) {
            samples[i] = Batch(action, loops);
            REQUIRE(samples[i] > 0, "nonpositive JSON benchmark duration");
            perCall[i] = samples[i] / loops;
        }
        std::sort(perCall.begin(), perCall.end());
        Bench::Print({name, perCall[REPEATS / 2], perCall.front(), perCall.back(), REPEATS});
        std::cout << "PROFILE_SAMPLES {\"case\":\"" << name << "\",\"inner_loops\":" << loops << ",\"samples_ns\":[";
        for (int i = 0; i < REPEATS; ++i)
            std::cout << (i ? "," : "") << samples[i];
        std::cout << "],\"per_iteration_ns\":[";
        for (int i = 0; i < REPEATS; ++i)
            std::cout << (i ? "," : "") << std::setprecision(17) << static_cast<double>(samples[i]) / loops;
        std::cout << "]}\n";
    }

    void Run(bool timed) {
        // Sealed 6a194df2 writer output: never regenerated by the current writer.
        const String_ legacy(JSON_PERF_LEGACY_FIXINGS_365);
        REQUIRE(legacy.size() == 10661 && CanonicalJson::FingerprintCanonical(std::string(legacy.data(), legacy.size())) ==
                                              "sha256:669a3e27b868e138edefa5fcfb9db5c9e56085163a9837fbf15243ae03e52ada",
                "JSON benchmark legacy bytes changed");
        Check(DailyFixings(365), legacy);
        CheckPreciseKeys();
        std::cout << "legacy_bytes=" << legacy.size() << " legacy_sha256=sha256:669a3e27b868e138edefa5fcfb9db5c9e56085163a9837fbf15243ae03e52ada\n";
        if (timed)
            Bench::PrintHeader();
        for (int count : {1, 365}) {
            const auto source = DailyFixings(count);
            const auto encoded = JSON::WriteString(source);
            Check(source, encoded);
            REQUIRE(JSON::WriteString(*JSON::ReadString(encoded, false)) == encoded, "Fixings JSON rewrite is unstable");
            std::cout << "FIXINGS_PREFLIGHT count=" << count << " own_bytes=" << encoded.size() << " exact_lookup=verified\n";
            if (timed) {
                const auto suffix = std::to_string(count);
                Measure("fixings-write-" + suffix, [&] {
                    const auto output = JSON::WriteString(source);
                    Bench::DoNotOptimize(&output);
                });
                Measure("fixings-read-own-" + suffix, [&] {
                    const auto output = JSON::ReadString(encoded, false);
                    Bench::DoNotOptimize(&output);
                });
            }
        }
        if (timed)
            Measure("fixings-read-legacy-365", [&] {
                const auto output = JSON::ReadString(legacy, false);
                Bench::DoNotOptimize(&output);
            });
    }
} // namespace

int main(int argc, char** argv) {
    if (argc > 2 || (argc == 2 && std::string(argv[1]) != "--preflight")) {
        std::cerr << "usage: json_perf [--preflight]\n";
        return 2;
    }
    try {
        RegisterAll_::Init();
        Run(argc == 1);
        return 0;
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
