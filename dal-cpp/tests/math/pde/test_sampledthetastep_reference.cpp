    struct StepReference_ {
        std::initializer_list<double> x_, rates_, drifts_, variances_, old_, seeds_, boundaries_;
        double dt_, theta_;
        std::array<bool, 2> external_;
        int layers_;
        std::initializer_list<double> solution_, oldRisk_, boundaryRisk_, rateRisk_, driftRisk_, varianceRisk_;
        double dtRisk_, thetaRisk_;
    };

    Matrix_<> ReferenceMatrix(int rows, int columns, std::initializer_list<double> data) {
        Matrix_<> result(rows, columns);
        auto value = data.begin();
        for (int row = 0; row < rows; ++row)
            for (int column = 0; column < columns; ++column)
                result(row, column) = *value++;
        return result;
    }

    void CheckReferenceValues(std::initializer_list<double> expected, const Matrix_<>& actual) {
        auto value = expected.begin();
        ASSERT_EQ(expected.size(), static_cast<size_t>(actual.Rows() * actual.Cols()));
        for (int row = 0; row < actual.Rows(); ++row)
            for (int column = 0; column < actual.Cols(); ++column) {
                ASSERT_NEAR(actual(row, column), *value, 1e-10 * std::max(1.0, std::abs(*value)));
                ++value;
            }
    }

    void CheckReferenceVector(std::initializer_list<double> expected, const Vector_<>& actual) {
        ASSERT_EQ(expected.size(), static_cast<size_t>(actual.size()));
        auto value = expected.begin();
        for (double actualValue : actual) {
            ASSERT_NEAR(actualValue, *value, 1e-10 * std::max(1.0, std::abs(*value)));
            ++value;
        }
    }

    void CheckStepReference(const StepReference_& reference) {
        SampledThetaStepInputs_ inputs;
        inputs.x_ = reference.x_;
        inputs.rates_ = reference.rates_;
        inputs.drifts_ = reference.drifts_;
        inputs.variances_ = reference.variances_;
        inputs.dt_ = reference.dt_;
        inputs.theta_ = reference.theta_;
        inputs.externalBoundaries_ = reference.external_;
        const int n = inputs.x_.size();
        inputs.oldValues_ = ReferenceMatrix(n, reference.layers_, reference.old_);
        inputs.externalValues_ = ReferenceMatrix(2, reference.layers_, reference.boundaries_);
        const SampledThetaStepPullback_ step(inputs, Dal::LinearSolveAccuracyPolicy_{1e-14, 1e-14});
        CheckReferenceValues(reference.solution_, step.Solution());
        const auto risk = step.Reverse(ReferenceMatrix(n, reference.layers_, reference.seeds_));
        CheckReferenceValues(reference.oldRisk_, risk.oldValues_);
        CheckReferenceValues(reference.boundaryRisk_, risk.externalValues_);
        CheckReferenceVector(reference.rateRisk_, risk.rates_);
        CheckReferenceVector(reference.driftRisk_, risk.drifts_);
        CheckReferenceVector(reference.varianceRisk_, risk.variances_);
        ASSERT_NEAR(risk.dt_, reference.dtRisk_, 1e-10);
        ASSERT_NEAR(risk.theta_, reference.thetaRisk_, 1e-10);
        ASSERT_EQ(risk.transposeBackwardErrors_.size(), reference.layers_);
        for (double error : risk.transposeBackwardErrors_)
            ASSERT_LE(error, 1e-14);
    }

